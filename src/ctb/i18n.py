STRINGS: Dict[str, Dict[str, str]] = {
    "en": EN,
    "he": HE,
}


def t(key: str, lang: Optional[str] = None, **kw) -> str:
    """Translate a UI key to English or Hebrew.

    If lang is omitted, checks kw['lang'], else uses active default.
    RTL marks are present ONLY in Hebrew values.
    """
    if "lang" in kw and lang is None:
        lang = kw.pop("lang")
    if not lang:
        lang = _current_lang
    lang = "he" if (lang or "").startswith("he") else "en"

    val = STRINGS[lang].get(key)
    if val is None:
        val = STRINGS["en"].get(key, key)
    if kw:
        try:
            return val.format(**kw)
        except Exception:
            return val
    return val


def t_he(key: str, **kw) -> str:
    """Return the Hebrew translation of key."""
    return t(key, lang="he", **kw)


def t_en(key: str, **kw) -> str:
    """Return the English translation of key."""
    return t(key, lang="en", **kw)


def both_langs(key: str, **kw) -> Tuple[str, str]:
    """Return a tuple of (Hebrew, English) translations for matching labels."""
    return (t(key, lang="he", **kw), t(key, lang="en", **kw))



